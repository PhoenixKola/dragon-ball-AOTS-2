"""Writes docs/BETA3_GAP_DECISIONS.md: one row per Beta 2 'missing' ID with its Beta 3 decision (from tools/beta3_decisions.py and the real installed files).
Usage: python -I tools/gen_beta3_gap_table.py"""
import csv, os, sys
from PIL import Image
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from beta3_decisions import DECISIONS, DECISIONS_EXTRA
ALL = {**DECISIONS, **DECISIONS_EXTRA}
base = list(csv.reader(open(os.path.join(ROOT, 'docs', 'FINAL_ART_ACCEPTANCE_BETA2.csv'), newline='', encoding='utf8')))[1:]
miss = [r for r in base if r[3] == 'missing']
FALL = {'guard': 'idle', 'charge': 'guard (idle)', 'special': 'attack', 'victory': 'idle', 'ko': 'hurt'}
out = ['# Beta 3 gap decisions (34 Beta 2 missing rows)', '',
       'Generated by `tools/gen_beta3_gap_table.py` from the frozen Beta 2 baseline (`docs/FINAL_ART_ACCEPTANCE_BETA2.csv`), `tools/beta3_decisions.py` and the installed files. '
       'Evidence = in-game pose gallery (`tools/beta3_pose_gallery.mjs`, dev server, 960x540 battle) in `evidence/beta3/gallery/`; before/after contacts in `art-sources/replaced-by-beta3/`.', '',
       '| ID | Beta 2 fallback | Candidate source | Decision | Installed path (size, bbox) | Evidence / runtime check | Reason |', '|---|---|---|---|---|---|---|']
counts = {}
for r in miss:
    i = r[0]; actor, _, pose = i.partition(':')
    d = ALL.get(i)
    if not d:
        out.append(f'| `{i}` | Beta 2: {r[8][:90]} | n/a | decided by the overworld stream | see report | see report | see `docs/FINAL_ART_ACCEPTANCE.csv` |'); continue
    counts[d[0]] = counts.get(d[0], 0) + 1
    p = f'public/assets/reviewed/actors/{actor}_{pose}.png'
    inst = '(none: fallback kept)'
    if os.path.exists(os.path.join(ROOT, p)):
        im = Image.open(os.path.join(ROOT, p)); bb = im.getchannel('A').point(lambda v: 255 if v > 8 else 0).getbbox()
        inst = f'`{p}` {im.width}x{im.height}, bbox {bb}'
    ev = f'`evidence/beta3/gallery/{actor.replace("soldier", "scout")}_{pose}.png`' if d[0] == 'accepted' else '`evidence/beta3/gallery/` (fallback rendered)'
    out.append(f'| `{i}` | {FALL.get(pose, "idle")} | `{d[1]}` | **{d[0]}** | {inst} | {ev}; no console errors | {d[2]} |')
out += ['', f'Counts over the {len(miss) - 2} battle rows decided here: {counts}. The two field rows (SSJ Trunks, Cooler) belong to the overworld stream.', '']
open(os.path.join(ROOT, 'docs', 'BETA3_GAP_DECISIONS.md'), 'w', encoding='utf8').write('\n'.join(out))
print(counts, len(miss))
