"""Generates src/data/spriteManifest.generated.ts from the actor PNGs: per-pose bounding box on the 176x176 canvas.
Usage: python -I tools/gen_sprite_manifest.py
All poses were found to be bottom-centre registered at (88, 172); the manifest still stores the real bbox.
"""
import glob, os, json
from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
d = os.path.join(ROOT, 'art-sources', 'archive', 'public-unused', 'actors')
out = {}
for p in sorted(glob.glob(os.path.join(d, '*.png'))):
    name = os.path.basename(p)[:-4]
    char, pose = name.rsplit('_', 1)
    bb = Image.open(p).convert('RGBA').getchannel('A').getbbox()
    out.setdefault(char, {})[pose] = list(bb)
# v4 additive pass: these sprites are installed straight into the live folder at a 352x352 canvas (tools/integrate_v4_actors.py); their boxes come from the live files.
LIVE_CHARS = ('dende', 'nail', 'zarbon2', 'soldier', 'gohan', 'krillin', 'piccolo', 'vegeta', 'goku', 'ssj_goku', 'cui', 'dodoria', 'zarbon', 'guldo', 'recoome', 'burter', 'jeice', 'ginyu', 'frieza1', 'frieza2', 'frieza3', 'frieza4', 'frieza5', 'cooler', 'trunks', 'trunks_ssj')
POSES = ('idle', 'attack', 'guard', 'hurt', 'charge', 'special', 'victory', 'ko')
_live = os.path.join(ROOT, 'public', 'assets', 'reviewed', 'actors')
for c in LIVE_CHARS:
    out[c] = {p: list(Image.open(os.path.join(_live, f'{c}_{p}.png')).convert('RGBA').getchannel('A').getbbox()) for p in POSES if os.path.exists(os.path.join(_live, f'{c}_{p}.png'))}
live = os.path.join(ROOT, 'public', 'assets', 'reviewed', 'actors')
lines = ['// GENERATED by tools/gen_sprite_manifest.py. Do not edit by hand.',
         'export type Box = [number, number, number, number];',
         'export const SPRITE_BOXES: Record<string, Record<string, Box>> = ' + json.dumps(out, indent=1) + ';', '']
open(os.path.join(ROOT, 'src', 'data', 'spriteManifest.generated.ts'), 'w').write('\n'.join(lines))
print(len(out), 'characters')
