"""Ground-burst aura 'rise' sequences (gold / purple; the red set is rejected: its frames overlap and clip when isolated) from AOTS2_additive_art_pack_v4/pixel_art_energy_effects_atlas.png.
Writes public/assets/reviewed/vfx/aura_rise/<colour>_<n>.png (144x144, base-centre anchor (72,140), glow preserved) and src/data/auraRise.generated.ts.
Usage: python -I tools/integrate_auras_v4.py"""
import os, sys, json
import numpy as np, cv2
from PIL import Image
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from v4_common import load

SRC = os.path.join(ROOT, 'art-sources', 'packs', 'AOTS2_additive_art_pack_v4', 'pixel_art_energy_effects_atlas.png')
OUT = os.path.join(ROOT, 'public', 'assets', 'reviewed', 'vfx', 'aura_rise')
C, AX, AY = 144, 72, 140
# seed points (x, y) on each growth frame, read from the numbered preview; order = growth order
SEEDS = {
    'gold': [(48, 128), (140, 118), (250, 100), (370, 100), (500, 100), (668, 90)],
    'purple': [(50, 635), (137, 605), (263, 612), (380, 605), (547, 610), (706, 610)],
}
im = load(SRC)
# per colour: (core alpha threshold, glow dilation). The red frames sit close together, so they need a tighter reach.
PARAMS = {'gold': (200, 25), 'purple': (200, 25)}
os.makedirs(OUT, exist_ok=True)
for col, seeds in SEEDS.items():
    thr, reach = PARAMS[col]
    strict = im[..., 3] >= thr
    k, lab, st, _ = cv2.connectedComponentsWithStats(cv2.dilate(strict.astype(np.uint8), np.ones((5, 5), np.uint8)))
    lab = np.where(strict, lab, 0)
    crops = []
    for (x, y) in seeds:
        sub = lab[max(0, y - 45):y + 45, max(0, x - 45):x + 45]
        ys, xs = np.nonzero(sub)
        j = int(np.argmin((xs - min(45, x)) ** 2 + (ys - min(45, y)) ** 2))
        cid = int(sub[ys[j], xs[j]])
        core = lab == cid
        grown = cv2.dilate(core.astype(np.uint8), np.ones((reach, reach), np.uint8)) > 0
        others = cv2.dilate(((lab > 0) & ~core).astype(np.uint8), np.ones((9, 9), np.uint8)) > 0
        m = grown & ~others & (im[..., 3] >= 40)
        out = im.copy(); out[..., 3] = np.where(m, im[..., 3], 0)
        ys2, xs2 = np.nonzero(m)
        crops.append(out[ys2.min():ys2.max() + 1, xs2.min():xs2.max() + 1])
    s = min(1.0, min(min((C - 6) / c.shape[1], (C - 8) / c.shape[0]) for c in crops))
    for n, c in enumerate(crops):
        h, w = c.shape[:2]
        pm = Image.fromarray(c).convert('RGBa').resize((max(1, round(w * s)), max(1, round(h * s))), Image.LANCZOS).convert('RGBA')
        canvas = Image.new('RGBA', (C, C), (0, 0, 0, 0))
        canvas.alpha_composite(pm, (AX - pm.width // 2, AY - pm.height))
        bb = canvas.getchannel('A').point(lambda v: 255 if v > 8 else 0).getbbox()
        assert bb[0] >= 1 and bb[1] >= 1 and bb[2] <= C - 1 and bb[3] <= C - 1, (col, n, bb)
        canvas.save(os.path.join(OUT, f'{col}_{n}.png'), optimize=True)
    print(col, round(s, 3))
reg = {c: {'frames': len(v), 'ms': 70, 'canvas': [C, C], 'anchor': [AX, AY]} for c, v in SEEDS.items()}
open(os.path.join(ROOT, 'src', 'data', 'auraRise.generated.ts'), 'w').write(
    '// GENERATED by tools/integrate_auras_v4.py. Do not edit by hand.\nexport interface AuraRiseFamily { frames: number; ms: number; canvas: [number, number]; anchor: [number, number] }\n'
    'export const AURA_RISE: Record<string, AuraRiseFamily> = ' + json.dumps(reg, indent=1) + ';\n')
